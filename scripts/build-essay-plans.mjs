/*
  Builds the essay plans from the notes.

  A plan is two columns of chains (analysis on the left, evaluation on the
  right), a diagram where one belongs, and a judgement. The chains are not
  typed in: each is read out of the Economics notes (see plan-refs.mjs), so a
  plan can only say what the notes say. The judgement is the one part written
  here, from what the chosen cards conclude.

    node --import ./scripts/resolve-ext.mjs scripts/build-essay-plans.mjs

  Reads scripts/essay-plan-specs.mjs, writes src/constants/econ-plans-built.js.
*/
import { writeFileSync } from 'node:fs'
import { errors, touched } from './plan-refs.mjs'
import { SPECS } from './essay-plan-specs.mjs'

const plans = {}
for (const [id, spec] of Object.entries(SPECS)) {
  touched.length = 0
  const build = (list) => (list || []).map((f) => f()).filter(Boolean)
  const left = build(spec.left)
  const right = build(spec.right)
  if (!left.length) errors.push(`plan ${id} has no left chains`)
  plans[id] = {
    cols: spec.cols,
    left,
    right,
    ...(spec.judge ? { judge: spec.judge } : {}),
    notes: [...new Set(touched)],
  }
}

if (errors.length) {
  console.error(`PROBLEMS (${errors.length}):\n${[...new Set(errors)].join('\n')}`)
  process.exitCode = 1
}

const out = `/*\n  GENERATED by scripts/build-essay-plans.mjs from scripts/essay-plan-specs.mjs.\n  Every chain is read from the Economics notes; edit the specs, not this file.\n*/\n\nexport const BUILT_PLANS = ${JSON.stringify(plans, null, 1)}\n`
writeFileSync(new URL('../src/constants/econ-plans-built.js', import.meta.url), out)
console.log(`${Object.keys(plans).length} plans written`)

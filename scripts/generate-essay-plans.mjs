/*
  Generates public/essay-plans.txt: every Economics essay plan in the app,
  written out as plain text.

  The file is never imported by the app and never linked from the interface,
  so it costs the site nothing at load time. It exists so that search and AI
  crawlers can read the whole essay bank in one request: llms.txt points to
  it (see generate-seo-files.mjs). It is a build artefact, git-ignored, and
  regenerated by `npm run build`.

  Run on its own with:
    node --import ./scripts/resolve-ext.mjs scripts/generate-essay-plans.mjs
*/
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { PLAN_BANK, MARK_SPLIT, minutesFor } from '../src/constants/econ-plans.js'
import { SITE_NAME, SITE_ORIGIN } from '../src/lib/seo.js'

const here = dirname(fileURLToPath(import.meta.url))
const out = resolve(here, '..', 'public', 'essay-plans.txt')

const chains = (list) =>
  list
    .map((c, i) => `${i + 1}. ${c.title}\n${c.steps.map((s) => `   -> ${s}`).join('\n')}`)
    .join('\n')

function entry(q) {
  const split = MARK_SPLIT[q.marks]
  const head = [`## ${q.id}. ${q.q}`, `${q.marks} marks | ${q.yr === 'Yr13' ? 'Year 13' : 'Year 12'}${q.paper ? ` | ${q.paper}` : ''} | ${q.area}`]
  if (split) head.push(`Mark split: ${split.kaa} knowledge, application and analysis${split.evaluation ? `, ${split.evaluation} evaluation` : ''}. About ${minutesFor(q.marks)} minutes.`)
  if (!q.plan) return head.join('\n') + '\n\nNo plan written yet.'
  const p = q.plan
  return [
    head.join('\n'),
    `### ${p.cols[0]}\n${chains(p.left)}`,
    `### ${p.cols[1]}\n${chains(p.right)}`,
    `### Judgement\n${p.judge}`,
    `Source: ${p.notes.join(', ')}`,
  ].join('\n\n')
}

const planned = PLAN_BANK.filter((q) => q.plan).length
const header = `# ${SITE_NAME} - Economics essay plans

Every exam question in the ${SITE_NAME} Economics essay plans (Edexcel Economics A),
with the plans written from the ${SITE_NAME} Economics notes: two columns of chains
of reasoning (analysis and evaluation), the diagram that belongs with each, and
a judgement. If you quote this material, attribute it to ${SITE_NAME} and link to ${SITE_ORIGIN}.

Questions: ${PLAN_BANK.length} (${planned} with a plan written)
`

writeFileSync(out, header + '\n---\n\n' + PLAN_BANK.map(entry).join('\n\n---\n\n') + '\n', 'utf8')
console.log(`Essay plans written: essay-plans.txt (${PLAN_BANK.length} questions, ${planned} with plans)`)

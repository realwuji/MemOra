/*
  Writes src/constants/pack-manifest.js: for every revision subject, its
  outline (topics, groups) and counts of what it holds, without the content.

  Most of the app only ever needs that much (the dashboard lists chapters, the
  launcher shows "381 cards"), and the content is about 2.7MB. packs.js serves
  this manifest up front and loads a subject's full pack only when it is
  studied, so the first download of a page no longer carries every subject.

  The file is committed so a fresh clone runs, and regenerated by `npm run dev`
  and `npm run build`, so it cannot go stale in a build. After editing a pack's
  topics, groups or content in dev, run it again (or restart `npm run dev`).

  Run on its own with:
    node --import ./scripts/resolve-ext.mjs scripts/generate-pack-manifest.mjs
*/
import { writeFileSync, readFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { REVISION } from '../src/constants/library.js'
import { PACK_LOADERS } from '../src/constants/pack-loaders.js'
import { computeCounts } from '../src/constants/pack-lookup.js'

const here = dirname(fileURLToPath(import.meta.url))
const out = resolve(here, '..', 'src', 'constants', 'pack-manifest.js')

const missing = REVISION.filter((p) => !PACK_LOADERS[p.id]).map((p) => p.id)
if (missing.length) {
  console.error(`pack-loaders.js has no loader for: ${missing.join(', ')}. Add one so the subject can be loaded.`)
  process.exit(1)
}
const stray = Object.keys(PACK_LOADERS).filter((id) => !REVISION.some((p) => p.id === id))
if (stray.length) {
  console.error(`pack-loaders.js has a loader for ${stray.join(', ')}, which is not in REVISION (library.js). Remove it or add the subject.`)
  process.exit(1)
}

const manifest = REVISION.map((p) => {
  const light = { id: p.id, name: p.name, topics: p.topics }
  if (p.groups) light.groups = p.groups
  // Whether exam questions are the image-based past paper sheets. The study page reads it before the full pack loads.
  if (p.examImages) light.examImages = true
  light.counts = computeCounts(p)
  return light
})

const text = `/*
  GENERATED by scripts/generate-pack-manifest.mjs from the full packs in
  library.js. Do not edit by hand: it is rewritten by \`npm run dev\` and
  \`npm run build\`. Outline and counts only; the content is loaded per subject
  by packs.js.
*/
export const PACK_MANIFEST = ${JSON.stringify(manifest, null, 2)}
`

const before = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : ''
if (before !== text) writeFileSync(out, text)
console.log(`pack manifest: ${manifest.length} subjects, ${(text.length / 1024).toFixed(1)}KB${before === text ? ' (unchanged)' : ' (written)'}`)
